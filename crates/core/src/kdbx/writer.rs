//! KDBX writer: re-encrypt an existing KDBX byte buffer through the vendored
//! keepassxcr backend.
//!
//! The backend derives a fresh KDF salt, master seed and encryption IV on every
//! save, and preserves unknown XML because it round-trips the whole database
//! model. This module is IO-free: callers pass bytes and receive bytes.
//!
//! Full model-to-database writing (edits, attachments, merges) is M1-04+ work;
//! this task establishes the byte-level write path and its verification.

use crate::kdbx::detect_version;
use keepassxcr::format::{read_kdbx_bytes, write_kdbx_bytes};
use keepassxcr::Credentials;
use std::fmt;

/// Write backend identity (also exposed in diagnostics).
pub const WRITE_BACKEND: &str = "keepassxcr 0.3.1 (vendored, byte API)";

/// Default output version for newly created databases.
pub const DEFAULT_WRITE_VERSION: &str = "4.0";

/// Error returned by the KDBX writer.
#[derive(Debug)]
pub enum KdbxWriteError {
    /// Header missing/unsupported.
    Header(String),
    /// Input could not be decrypted.
    Read(String),
    /// Output could not be encrypted.
    Write(String),
}

impl fmt::Display for KdbxWriteError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Header(message) => write!(f, "invalid KDBX header: {message}"),
            Self::Read(message) => write!(f, "cannot read KDBX: {message}"),
            Self::Write(message) => write!(f, "cannot write KDBX: {message}"),
        }
    }
}

impl std::error::Error for KdbxWriteError {}

/// Re-encrypt `bytes` (same database contents) with the selected backend.
///
/// A fresh KDF salt, master seed and IV are generated by the backend on every
/// call, so two calls on the same input produce different bytes. The format
/// version is preserved (M1-03 default-write policy for new empty databases is
/// `DEFAULT_WRITE_VERSION`; version upgrades are a separate operation).
pub fn reseal(bytes: &[u8], password: &str) -> Result<Vec<u8>, KdbxWriteError> {
    let header = bytes
        .get(..12)
        .ok_or_else(|| KdbxWriteError::Header("shorter than 12 bytes".to_string()))?;
    detect_version(header).map_err(|error| KdbxWriteError::Header(error.to_string()))?;
    if password.is_empty() {
        return Err(KdbxWriteError::Read(
            "password required to re-encrypt".to_string(),
        ));
    }

    let credentials = Credentials::password(password);
    let file = read_kdbx_bytes(bytes, &credentials)
        .map_err(|error| KdbxWriteError::Read(format!("{error:?}")))?;
    write_kdbx_bytes(&file, &credentials)
        .map_err(|error| KdbxWriteError::Write(format!("{error:?}")))
}

/// Version that the backend uses for `KdbxFile::new` (new databases).
pub fn new_database_version() -> &'static str {
    match keepassxcr::KdbxFile::new(keepassxcr::Database::new("keepassity".into())).version {
        keepassxcr::format::KdbxVersion::V4_0 => "4.0",
        keepassxcr::format::KdbxVersion::V4_1 => "4.1",
        keepassxcr::format::KdbxVersion::V3_1 => "3.1",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn backend_default_version_is_4_0() {
        assert_eq!(new_database_version(), DEFAULT_WRITE_VERSION);
    }

    #[test]
    fn rejects_truncated_input() {
        assert!(matches!(
            reseal(&[0u8; 4], "x"),
            Err(KdbxWriteError::Header(_))
        ));
    }
}
